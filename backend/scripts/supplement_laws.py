async def supplement_laws():
    from tortoise import Tortoise

    db_url = "postgres://legal_user:legal_pass@localhost:5432/legal_db"
    await Tortoise.init(
        db_url=db_url,
        modules={"models": ["app.models.case", "app.models.law"]},
        _enable_global_fallback=True,
        use_tz=False,
    )

    from app.models.law import Law

    updated_count = 0

    for supp in SUPPLEMENTS:
        law_id = supp["law_id"]
        new_text = supp["text"]

        # 1. 更新 PostgreSQL
        law = await Law.filter(id=law_id).first()
        if law is None:
            print(f"  [跳过] 法条 {law_id} 不在数据库中")
            continue

        # 检查是否已包含（防止重复追加）
        check_str = supp.get("check", new_text.strip()[:20])
        if check_str in (law.content or ""):
            print(f"  [已有] {law.title} — 条文已存在")
            continue

        law.content = (law.content or "") + new_text
        await law.save()
        updated_count += 1
        print(f"  [追加] {law.title} — 已补充新条文")

    # 2. 更新 v2 JSON（如果存在）
    v2_path = os.path.join(os.path.dirname(__file__), "..", "data", "legal_eval_dataset_v2.json")
    if os.path.exists(v2_path):
        with open(v2_path, encoding="utf-8") as f:
            v2_data = json.load(f)

        json_updated = 0
        for supp in SUPPLEMENTS:
            for law in v2_data.get("laws", []):
                if law["id"] == supp["law_id"]:
                    check_str = supp.get("check", supp["text"].strip()[:20])
                    if check_str not in law["content"]:
                        law["content"] += supp["text"]
                        json_updated += 1
                    break

        with open(v2_path, "w", encoding="utf-8") as f:
            json.dump(v2_data, f, ensure_ascii=False, indent=2)
        print(f"\n  JSON 更新：{json_updated} 条法条已追加到 {v2_path}")
    else:
        print(f"\n  JSON 跳过：{v2_path} 不存在")

    # 3. 同步更新 v1 JSON
    v1_path = os.path.join(os.path.dirname(__file__), "..", "data", "legal_eval_dataset.json")
    if os.path.exists(v1_path):
        with open(v1_path, encoding="utf-8") as f:
            v1_data = json.load(f)

        for supp in SUPPLEMENTS:
            for law in v1_data.get("laws", []):
                if law["id"] == supp["law_id"]:
                    check_str = supp.get("check", supp["text"].strip()[:20])
                    if check_str not in law["content"]:
                        law["content"] += supp["text"]
                    break

        with open(v1_path, "w", encoding="utf-8") as f:
            json.dump(v1_data, f, ensure_ascii=False, indent=2)
        print(f"  JSON 更新：v1 数据也已同步")

    print(f"\n  共更新 {updated_count} 条法条")
    print("  请运行 build_index.py 重建向量索引")

    await Tortoise.close_connections()


if __name__ == "__main__":
    print("== 补充缺失法条 ==")
    asyncio.run(supplement_laws())
    print("== 完成 ==")
